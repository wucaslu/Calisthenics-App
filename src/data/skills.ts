// Add definitions here. Reverse unlock links are derived below to avoid two sources of truth.
function define(
  id: string,
  name: string,
  category: Category,
  branch: Branch,
  fallbackDifficulty: DifficultyLevel,
  movementType: MovementType,
  prerequisites: string[],
  equipment: Equipment[],
  description: string,
  target: string,
  drills: Skill["exercises"],
): Skill {
  const muscles = skillMuscles[id];
  if (!muscles) throw new Error(`Missing muscle profile for skill: ${id}`);
  const technique = skillTechnique[id];
  if (!technique)
    throw new Error(`Missing technique guidance for skill: ${id}`);
  const sourceLevel = og2Levels[id];
  return {
    id,
    name,
    category,
    branch,
    difficulty: sourceLevel?.level ?? fallbackDifficulty,
    levelSource: sourceLevel?.kind,
    movementType,
    prerequisites,
    equipment,
    alternativeRoutes: alternativeRoutes[id],
    equipmentSetups: equipmentSetups[id],
    description,
    muscles,
    technique,
    progressionTo: [],
    requirements: [{ exercise: name, target }],
    exercises: drills,
    references: skillReferences[id]?.sources ?? [],
    referenceLevel: skillReferences[id]?.level,
  };
}
const hold = (
  name: string,
  duration: string,
  description: string,
): Skill["exercises"][number] => ({
  name,
  sets: "3",
  hold: duration,
  description,
});
