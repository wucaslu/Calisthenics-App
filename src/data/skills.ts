// Add definitions here. Reverse unlock links are derived below to avoid two sources of truth.
function define(
  id: string,
  name: string,
  category: Category,
  branch: Branch,
  difficulty: number,
  prerequisites: string[],
  equipment: Equipment[],
  description: string,
  target: string,
  drills: Skill["exercises"],
): Skill {
  return {
    id,
    name,
    category,
    branch,
    difficulty,
    prerequisites,
    equipment,
    description,
    progressionTo: [],
    requirements: [{ exercise: name, target }],
    exercises: drills,
  };
}
const hold = (
  name: string,
  duration: string,
  description: string,
): Skill["exercises"][number] => ({
  name,
  sets: "3",
  hold: duration,
  description,
});
